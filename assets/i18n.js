export const LANGS = ['sk', 'en'];

function initialLang() {
  try { const l = localStorage.getItem('adacta-lang'); if (LANGS.includes(l)) return l; } catch { /* stockage indisponible */ }
  return /^(sk|cs)/i.test(navigator.language || '') ? 'sk' : 'en';
}

let lang = initialLang();
export const getLang = () => lang;
export const locale = () => (lang === 'sk' ? 'sk-SK' : 'en-GB');
export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'sk';
  try { localStorage.setItem('adacta-lang', lang); } catch { /* stockage indisponible */ }
  document.documentElement.lang = lang;
}

/** t('list.count', {orders: 3}) — les variables sont insérées telles quelles. */
export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

document.documentElement.lang = lang;
